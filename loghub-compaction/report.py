#!/usr/bin/env python3
"""
Render results/results.json, results/results.md and the README's table from the per-corpus
records (results/<corpus>.json) and set each against the compaction ledger (ledger.json).

`--check` renders them again and fails if the committed results.json or the README's
generated table differ, so a figure edited without a rerun is caught in CI.
"""
import argparse
import csv
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent

# README blocks: the text between `<!-- generated:NAME -->` and `<!-- /generated:NAME -->` is
# written from the results and compared by --check.
BLOCK = re.compile(r'<!-- generated:([a-z0-9-]+) -->\n(.*?)<!-- /generated:\1 -->', re.S)


def apply_blocks(text: str, blocks: dict) -> str:
    missing = sorted(set(blocks) - {m.group(1) for m in BLOCK.finditer(text)})
    if missing:
        raise SystemExit(f'README.md has no generated block for: {", ".join(missing)}')
    return BLOCK.sub(lambda m: f'<!-- generated:{m.group(1)} -->\n{blocks[m.group(1)].rstrip()}\n<!-- /generated:{m.group(1)} -->'
                     if m.group(1) in blocks else m.group(0), text)


def differing_blocks(text: str, blocks: dict) -> list:
    committed = {m.group(1): m.group(2).rstrip() for m in BLOCK.finditer(text)}
    return sorted(n for n, body in blocks.items() if committed.get(n) != body.rstrip())

OVER_100MB = 100_000_000


def corpora():
    with open(HERE / 'corpora.tsv') as f:
        return [r['corpus'] for r in csv.DictReader(f, delimiter='\t')]


def compute() -> dict:
    ledger = json.load(open(HERE / 'ledger.json'))
    rows = []
    for name in corpora():
        r = json.load(open(HERE / 'results' / f'{name}.json'))
        compact = r['encoded_bytes'] + r['templates_bytes']
        exp = ledger['corpora'][name]
        diffs = {k: [r[k] if k != 'compact_bytes' else compact, exp[k]]
                 for k in ('events', 'input_bytes', 'compact_bytes', 'templates')
                 if (r[k] if k != 'compact_bytes' else compact) != exp[k]}
        rows.append({
            'corpus': name,
            'input_files': r['input_files'],
            'raw_lines': r['raw_lines'],
            'events': r['events'],
            'input_bytes': r['input_bytes'],
            'encoded_bytes': r['encoded_bytes'],
            'templates_bytes': r['templates_bytes'],
            'compact_bytes': compact,
            'reduction_pct': round((1 - compact / r['input_bytes']) * 100, 4),
            'ratio': round(r['input_bytes'] / compact, 2),
            'templates': r['templates'],
            'sha256_encoded': r['sha256_encoded'],
            'sha256_templates': r['sha256_templates'],
            'differs_from_ledger': diffs,
        })
    total_in = sum(x['input_bytes'] for x in rows)
    total_c = sum(x['compact_bytes'] for x in rows)
    big = [x for x in rows if x['input_bytes'] > OVER_100MB]
    return {
        'image': json.load(open(HERE / 'results' / f'{rows[0]["corpus"]}.json'))['image'],
        'config_sha256': __import__('hashlib').sha256((HERE / 'tenx-encode.config.yaml').read_bytes()).hexdigest(),
        'corpora': rows,
        'aggregate': {
            'events': sum(x['events'] for x in rows),
            'input_bytes': total_in,
            'compact_bytes': total_c,
            'reduction_pct': round((1 - total_c / total_in) * 100, 4),
            'over_100mb': [x['corpus'] for x in big],
            'over_100mb_reduction_pct': round((1 - sum(x['compact_bytes'] for x in big) / sum(x['input_bytes'] for x in big)) * 100, 4),
        },
        'ledger_source': ledger['source'],
    }


def pct(v):
    return f'{v:.1f}%' if round(v, 1) != round(v) else f'{v:.0f}%'


def table(r: dict) -> str:
    L = ['| Corpus | Events | Input | Compact (encoded + dictionary) | Reduction | Ratio | Templates | Against the ledger |',
         '|---|---:|---:|---:|---:|---:|---:|---|']
    for x in sorted(r['corpora'], key=lambda x: -x['reduction_pct']):
        d = x['differs_from_ledger']
        note = 'equal' if not d else '; '.join(f'{k.replace("_", " ")} {v[0]:,} against {v[1]:,}' for k, v in d.items())
        L.append(f'| {x["corpus"]} | {x["events"]:,} | {x["input_bytes"]:,} B | {x["compact_bytes"]:,} B | {pct(x["reduction_pct"])} | '
                 f'{x["ratio"]:g}x | {x["templates"]:,} | {note} |')
    a = r['aggregate']
    L.append('')
    L.append(f'**All 14:** {a["events"]:,} events, {a["input_bytes"]:,} B in, {a["compact_bytes"]:,} B compact, byte-weighted reduction '
             f'{pct(a["reduction_pct"])}. The {len(a["over_100mb"])} over 100 MB ({", ".join(a["over_100mb"])}): {pct(a["over_100mb_reduction_pct"])}.')
    return '\n'.join(L)


def render(r: dict) -> str:
    L = ['# LogHub compaction results', '',
         f'Generated by `report.py` from `results/<corpus>.json`. Engine image `{r["image"]}`; config `tenx-encode.config.yaml` sha256 `{r["config_sha256"]}`.', '',
         table(r), '',
         '## Output hashes', '',
         '| Corpus | Input files | Raw lines | encoded.log | templates.json |', '|---|---:|---:|---|---|']
    for x in r['corpora']:
        L.append(f'| {x["corpus"]} | {x["input_files"]:,} | {x["raw_lines"]:,} | {x["encoded_bytes"]:,} B, `{x["sha256_encoded"]}` | '
                 f'{x["templates_bytes"]:,} B, `{x["sha256_templates"]}` |')
    L.append('')
    return '\n'.join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    r = compute()
    blocks = {'table': table(r)}
    if a.check:
        committed = json.load(open(HERE / 'results' / 'results.json'))
        if committed != r:
            raise SystemExit('results.json does not follow from the per-corpus records')
        stale = differing_blocks((HERE / 'README.md').read_text(), blocks)
        if stale:
            raise SystemExit(f'README.md differs from the results in: {", ".join(stale)}; run report.py to rewrite them')
        print(f'the committed figures follow from the per-corpus records: {r["aggregate"]["events"]:,} events, '
              f'byte-weighted reduction {pct(r["aggregate"]["reduction_pct"])}')
        return 0
    json.dump(r, open(HERE / 'results' / 'results.json', 'w'), indent=1)
    (HERE / 'results' / 'results.md').write_text(render(r))
    readme = HERE / 'README.md'
    if readme.exists():
        readme.write_text(apply_blocks(readme.read_text(), blocks))
    print('wrote results/results.json, results/results.md and the README table')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
