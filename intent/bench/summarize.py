#!/usr/bin/env python3
"""Print results/results.md from the score files in results/."""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(HERE), 'results')
CAPTURES = ('otel215', 'rec1155')
MAIN = [('engine-1.1.132', '10x engine 1.1.132'), ('engine-1.1.133', '10x engine 1.1.133'),
        ('drain3-strong-event', 'Drain3, strong arm'), ('drain3-baseline-event', 'Drain3, baseline arm')]
SENSITIVITY = [('drain3-strong-record', 'Drain3, strong arm, per record'),
               ('drain3-baseline-record', 'Drain3, baseline arm, per record')]


def load(tag, cap, suffix=''):
    p = os.path.join(RES, f'{tag}_{cap}{suffix}.json')
    return json.load(open(p)) if os.path.exists(p) else None


def n(x):
    return f'{x:,}'


def grouping_table(rows, cap, suffix=''):
    out = ['| tool | events scored | merged events | split events | exact grouping | statements with one pattern of their own | patterns |',
           '|---|---:|---:|---:|---:|---:|---:|']
    for tag, label in rows:
        r = load(tag, cap, suffix)
        if not r:
            continue
        o = r['overall']
        out.append(f"| {label} | {n(o['events'])} | {o['merged_event_share']}% ({n(o['merged_events'])}) | "
                   f"{o['split_event_share']}% | {o['exact_grouping_events']}% | {o['statements_clean']}% "
                   f"of {o['statements']} | {n(r['distinct_patterns'])} |")
    return '\n'.join(out)


def library_table(cap):
    out = ['| tool | source in the 1.1.89 library: merged / exact | source not in it: merged / exact | not code: merged / exact |',
           '|---|---|---|---|']
    for tag, label in MAIN:
        r = load(tag, cap)
        if not r:
            continue
        cells = []
        for g in ('source_in_library', 'source_not_in_library', 'not_code'):
            o = r['by_group'].get(g)
            cells.append(f"{o['merged_event_share']}% / {o['exact_grouping_events']}% ({n(o['events'])} events, "
                         f"{o['statements']} statements)" if o else 'n/a')
        out.append(f'| {label} | ' + ' | '.join(cells) + ' |')
    return '\n'.join(out)


def engine_table(cap):
    out = ['| engine | untyped | exact file | same repository, other file | other project | name starts with the statement\'s first word | name carries a severity or envelope word |',
           '|---|---:|---:|---:|---:|---:|---:|']
    for tag, label in MAIN[:2]:
        r = load(tag, cap)
        if not r:
            continue
        o = r['overall']
        out.append(f"| {label} | {o['attr_untyped']}% | {o['attr_exact_file']}% | {o['attr_same_repo_other_file']}% | "
                   f"{o['attr_other_project']}% | {o['name_first']}% | {o['name_sev_or_env']}% |")
    return '\n'.join(out)


def drain_stats():
    out = ['| run | messages | clusters | distinct names | unmatched |', '|---|---:|---:|---:|---:|']
    for cap in CAPTURES:
        for tag, label in MAIN[2:] + SENSITIVITY:
            p = os.path.join(RES, f'{tag}_{cap}_stats.json')
            if os.path.exists(p):
                s = json.load(open(p))
                out.append(f"| {label}, {cap} | {n(s['messages'])} | {n(s['clusters'])} | {n(s['distinct_names'])} | {s['unmatched']} |")
    return '\n'.join(out)


def main():
    print('# Results\n')
    print('Generated by `bench/summarize.py` from the score files in this folder.\n')
    for cap in CAPTURES:
        print(f'## {cap}\n')
        print(grouping_table(MAIN, cap) + '\n')
        print(f'Without the opentelemetry-collector container:\n')
        print(grouping_table(MAIN, cap, '_without-collector') + '\n')
        print('By where the statement\'s source is:\n')
        print(library_table(cap) + '\n')
        print('Engine only, events whose statement is code:\n')
        print(engine_table(cap) + '\n')
        print('Drain3 fed one message per record, an event named by its first record:\n')
        print(grouping_table(SENSITIVITY, cap) + '\n')
    print('## Drain3 runs\n')
    print(drain_stats())


if __name__ == '__main__':
    main()
