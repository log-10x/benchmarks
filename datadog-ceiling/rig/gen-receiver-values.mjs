// Writes the Receiver values log10x-mcp renders for a Datadog Fluent Bit Receiver that counts
// events and pulls its policy files from git, through the functions log10x_advise_install
// calls (receiverFleetValues with regulator_unit "events", then the Fluent Bit overlay's
// renderValues with the Datadog metrics backend and policy_git), and a compose overlay that
// launches rig-tenx with them.
//   MCP=<log10x-mcp package> node gen-receiver-values.mjs <out dir> <owner/repo> <branch>
//
// Outputs in <out dir>:
//   values.yaml           the rendered Fluent Bit chart overlay, verbatim
//   receiver-values.json  receiverFleetValues' result, verbatim
//   seed.sh               the install's seed step for the policy branch, verbatim
//   compose.receiver.yaml the rig-tenx service: the values' image, args and env
//   launch.json           what was applied, what was substituted, and why
//
// Applied as written: the image, every arg in order, every env var with a plain value.
// Substituted, because there is no cluster: env vars the values read from a Secret
// (GH_TOKEN, DD_API_KEY, DD_APP_KEY) are passed from the shell environment by name, so no
// key is written to a file.
// Rig plumbing: TENX_FLUENTBIT_OUTPUT_HOST=fluent-bit (Fluent Bit is a separate container).
// Measurement only, after every MCP arg: outputEncodeField adds message_pattern and
// severity_level to the returned record.
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { resolve, join } from 'path';

const MCP = process.env.MCP;
if (!MCP) throw new Error('set MCP to a log10x-mcp package');
const [outArg, repo, branch] = process.argv.slice(2);
if (!outArg || !repo || !branch) throw new Error('usage: gen-receiver-values.mjs <out dir> <owner/repo> <branch>');
const out = resolve(outArg);
mkdirSync(out, { recursive: true });

const { receiverFleetValues } = await import(`${MCP}/build/lib/fleet-default-install.js`);
const { RECEIVER_FORWARDER_SPECS, renderPolicyGitSeedCommands } = await import(`${MCP}/build/lib/advisor/reporter-forwarders.js`);
const mcpVersion = JSON.parse(readFileSync(`${MCP}/package.json`, 'utf8')).version;

const values = receiverFleetValues({ datadog: true, unit: 'events', keepCount: 50 });
if (!values.eventsUnitWritten || !values.keepCountsWritten) throw new Error(`events unit or keep counts not written: ${values.notes.join(' ')}`);
writeFileSync(join(out, 'receiver-values.json'), JSON.stringify(values, null, 1) + '\n');

const policyGit = { repo, branch, tokenSecretName: 'log10x-policy-git' };
const yaml = RECEIVER_FORWARDER_SPECS.fluentbit.renderValues({
  releaseName: 'rig',
  destination: 'datadog',
  builtinLicense: true,
  airgapped: true,
  licenseSecretName: 'log10x-license',
  licenseSecretKey: 'license.jwt',
  backends: ['datadog'],
  engineOptions: values.options,
  engineEnv: values.env,
  policyGit,
});
writeFileSync(join(out, 'values.yaml'), yaml);
writeFileSync(join(out, 'seed.sh'), renderPolicyGitSeedCommands(policyGit, 'events') + '\n');

const block = yaml.slice(yaml.indexOf('  - name: log10x'));
const image = /\n\s+image: (\S+)/.exec(block)[1];
const argsText = block.split('\n    args:\n')[1].split('\n    env:\n')[0];
const args = argsText.split('\n').map((l) => /^\s+- "(.*)"$/.exec(l)).filter(Boolean).map((m) => m[1]);
const envText = block.split('\n    env:\n')[1].split(/\n    [a-zA-Z]/)[0];
const env = [];
for (const m of envText.matchAll(/- name: (\S+)\n((?:\s{8,}.*\n?)+)/g)) {
  const body = m[2];
  const v = /^\s+value: (.*)$/m.exec(body);
  env.push({ name: m[1], value: v ? v[1].replace(/^"(.*)"$/, '$1') : undefined, valueFrom: v ? undefined : body.trim() });
}

const FROM_SHELL = new Set(['GH_TOKEN', 'DD_API_KEY', 'DD_APP_KEY']);
const LEFT_OUT = new Set();
const applied = [];
const fromShell = [];
const left = [];
for (const e of env) {
  if (FROM_SHELL.has(e.name)) fromShell.push(e);
  else if (LEFT_OUT.has(e.name)) left.push(e);
  else if (e.value !== undefined) applied.push(e);
  else left.push(e);
}
const rigEnv = [['TENX_FLUENTBIT_OUTPUT_HOST', 'fluent-bit']];
const measure = ['outputEncodeField', 'fullText("tenx_hash","routeState","message_pattern","severity_level")'];

const q = (s) => JSON.stringify(String(s)).replace(/\$/g, '$$$$');
const res = /limits:\s*\{\s*cpu:\s*(\S+),\s*memory:\s*(\S+)\s*\}/.exec(block);
const cpu = res ? (res[1].endsWith('m') ? String(Number(res[1].slice(0, -1)) / 1000) : res[1]) : undefined;
const mem = res ? res[2].replace(/Mi$/, 'M').replace(/Gi$/, 'G') : undefined;
const lines = [
  '# Generated by rig/gen-receiver-values.mjs from values.yaml in this directory. Do not edit.',
  'services:',
  '  tenx:',
  `    image: ${q(image)}`,
  '    container_name: rig-tenx',
  '    environment:',
  ...applied.map((e) => `      - ${q(`${e.name}=${e.value}`)}`),
  ...fromShell.map((e) => `      - ${q(e.name)}`),
  ...rigEnv.map(([k, v]) => `      - ${q(`${k}=${v}`)}`),
  '    tmpfs:',
  '      - /tmp',
  '    command:',
  ...args.map((a) => `      - ${q(a)}`),
  ...measure.map((a) => `      - ${q(a)}`),
  ...(cpu || mem
    ? ['    deploy:', '      resources:', '        limits:', ...(cpu ? [`          cpus: ${q(cpu)}`] : []), ...(mem ? [`          memory: ${q(mem)}`] : [])]
    : []),
  '    restart: unless-stopped',
  '',
];
writeFileSync(join(out, 'compose.receiver.yaml'), lines.join('\n'));
const launch = {
  mcp_version: mcpVersion,
  image,
  args_from_values: args,
  env_from_values: env,
  env_applied: applied,
  env_from_shell_by_name: fromShell.map((e) => e.name),
  env_left_out: left.map((e) => e.name),
  rig_env: rigEnv,
  measurement_args: measure,
  resources_limits: { cpus: cpu, memory: mem },
  policy_git: policyGit,
  notes: values.notes,
};
writeFileSync(join(out, 'launch.json'), JSON.stringify(launch, null, 1) + '\n');
console.log(JSON.stringify({ mcpVersion, image, args, applied: applied.map((e) => `${e.name}=${e.value}`), fromShell: fromShell.map((e) => e.name), left: left.map((e) => e.name), cpu, mem }, null, 1));
